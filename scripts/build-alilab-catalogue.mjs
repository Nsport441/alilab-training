// Offline, deterministic import of the pinned openGym text snapshot. Never downloads media.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'catalogue', name), 'utf8'))
const source = read('upstream.json'), legacy = read('legacy.json'), provenance = read('provenance.json')
const ids = new Set()
for (const e of source) {
  if (!/^\d{4,5}$/.test(e.id) || ids.has(e.id)) throw Error('Invalid/duplicate source ID: ' + e.id)
  ids.add(e.id)
}
const canonical = source.filter(e => !e.variantOf), index = new Map(canonical.map(e => [e.id, e]))
if (canonical.length !== provenance.independentExercises || source.length !== provenance.sourceRecords) throw Error('Source count mismatch')
for (const e of legacy) {
  if (index.get(e.id)?.name !== e.n) throw Error('Legacy identity changed: ' + e.id)
}
const aliases = Object.fromEntries(source.filter(e => e.variantOf).map(e => {
  if (!index.has(e.variantOf) || index.has(e.id)) throw Error('Invalid variant: ' + e.id)
  return [e.id, e.variantOf]
}))
const legacyOrder = new Map(legacy.map((e,i) => [e.id,i]))
// Keep the familiar first page stable; new entries follow it in deterministic name order.
const rows = canonical.sort((a,b) => {
  const ai=legacyOrder.get(a.id), bi=legacyOrder.get(b.id)
  if (ai!=null || bi!=null) return (ai ?? Infinity)-(bi ?? Infinity)
  return a.name < b.name ? -1 : a.name > b.name ? 1 : a.id.localeCompare(b.id)
}).map(e => {
  if (!e.name || !e.bodyPart || !e.equipment || !e.target || !Array.isArray(e.instructions) || !e.instructions.length) throw Error('Incomplete exercise: ' + e.id)
  const row = { id:e.id, n:e.name, bp:e.bodyPart, eq:e.equipment, tg:e.target,
    mg:e.secondaryMuscles[0] || '', sm:e.secondaryMuscles, st:e.instructions,
    img:e.id+'.webp', gif:e.id+'.mp4', cat:e.category, desc:e.description }
  if (e.hold) row.hd = 1
  if (e.needs) row.nd = e.needs
  if (e.femaleVariant) row.fv = e.femaleVariant
  if (e.maleVariant) row.mv = e.maleVariant
  if (e.muscleMap) {
    const m=e.muscleMap
    if (m.bodyPart) row.bp=m.bodyPart
    if (m.primaries) row.primaries=m.primaries
    if (m.secondaries) row.secondaries=m.secondaries
    if (m.weights) row.muscleWeights=m.weights
  }
  return row
})
const json = v => `JSON.parse(${JSON.stringify(JSON.stringify(v))})`
const outputs = {
  'frontend/src/lib/exercises-data.js': `// Generated by scripts/build-alilab-catalogue.mjs; source and licences in catalogue/.\nexport const EXDB=${json(rows)}\nexport const EXALIAS=${json(aliases)}\n`,
  'frontend/src/lib/legacy-cardio.js': '// Generated historical classification: never reinterpret pre-mode saved workouts.\n' +
    `export const LEGACY_CARDIO_IDS = new Set(${JSON.stringify(legacy.filter(e=>e.bp==='cardio').map(e=>e.id))})\n` +
    `export const LEGACY_IDS = new Set(${JSON.stringify(legacy.map(e=>e.id))})\n`
}
for (const [rel,body] of Object.entries(outputs)) {
  const p=path.join(root,rel)
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n')!==body) throw Error('Stale generated catalogue: '+rel)
  } else fs.writeFileSync(p,body)
}
console.log(`Catalogue: ${rows.length} independent exercises, ${Object.keys(aliases).length} variant aliases; all legacy identities preserved`)
