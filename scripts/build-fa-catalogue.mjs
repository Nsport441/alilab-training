const dictionary = Object.entries({...words,...phrases}).sort((a,b)=>b[0].length-a[0].length)
const unknown = new Set()
function translateName(name) {
  let src=name.replace(/[-]/g,' ').replace(/\bv\.\s*(\d+)/g,'نوع $1').replace(/\s+/g,' ').trim()
  let eq=''
  for(const [key,value] of Object.entries(equipment)) {
    if(src.startsWith(key+' ')){src=src.slice(key.length).trim();eq=value;break}
  }
  const tokens=[]
  while(src.length){
    const match=dictionary.find(([key])=>src===key || (src.startsWith(key)&&!/[a-z]/.test(src[key.length])))
    if(match){tokens.push(match[1]);src=src.slice(match[0].length).trim();continue}
    const ch=src.match(/^[a-z]+/)
    if(ch){unknown.add(ch[0]);tokens.push(ch[0]);src=src.slice(ch[0].length).trim()}
    else {const value=src.match(/^[\p{L}\p{N}]+/u)?.[0]||src[0];tokens.push(value);src=src.slice(value.length).trim()}
  }
  return (tokens.filter(Boolean).join(' ').replace(/\s+([),])/g,'$1').replace(/([(])\s+/g,'$1').replace(/\s+/g,' ').trim()+' '+eq).trim()
}
